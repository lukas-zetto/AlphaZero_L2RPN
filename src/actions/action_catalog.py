def compute_action_mask(observation, catalog: ActionCatalog) -> np.ndarray:
    """Compute a boolean mask (True = legal/keep) for the catalog based on cooldowns.

    Currently checks:
    - All involved lines have zero cooldown (time_before_cooldown_line == 0) for any change.
    - Placeholder hooks for future unsafe / islanding / security checks.

    If an action assigns a line end to the *same bus* it already is, we still allow it; we
    rely on drop_identity to remove pure no-ops. Mixed partial no-ops are fine.
    """
    size = catalog.size
    mask = np.ones(size, dtype=bool)

    # Fast path: required attributes missing -> return all True
    if not hasattr(observation, 'time_before_cooldown_line'):
        return mask

    line_cooldowns = observation.time_before_cooldown_line

    for idx, layout in enumerate(catalog.actions):
        # If any line end belongs to a line with cooldown, mask out.
        # We approximate: if either origin or extremity index appears and that line cooldown >0.
        # Need mapping from line end index to line id. In Grid2Op, line_or / line_ex indices are line ids.
        for line_id in layout.line_or_indices + layout.line_ex_indices:
            if line_id < len(line_cooldowns) and line_cooldowns[line_id] > 0:
                mask[idx] = False
                break
        # Future hooks:
        # if _would_be_unsafe(layout, observation): mask[idx] = False

    return mask

