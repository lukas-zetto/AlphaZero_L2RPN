def _gather_substation_elements(env, sub_id: int) -> List[Element]:
    """Collect all switchable elements in a deterministic order.
    Order: line_or, line_ex, gen, load (ascending indices in each group)."""
    elements: List[Element] = []
    line_or_indices = np.where(env.line_or_to_subid == sub_id)[0]
    for idx in line_or_indices:
        elements.append(("line_or", int(idx)))
    line_ex_indices = np.where(env.line_ex_to_subid == sub_id)[0]
    for idx in line_ex_indices:
        elements.append(("line_ex", int(idx)))
    gen_indices = np.where(env.gen_to_subid == sub_id)[0]
    for idx in gen_indices:
        elements.append(("gen", int(idx)))
    load_indices = np.where(env.load_to_subid == sub_id)[0]
    for idx in load_indices:
        elements.append(("load", int(idx)))
    return elements

def _enumerate_substation_layouts(env, sub_id: int, reduction: str, drop_identity: bool, baseline_obs) -> List[SubstationLayoutAction]:
    elements = _gather_substation_elements(env, sub_id)
    n = len(elements)
    if n == 0:
        return []

    # Baseline bus assignment per element (fallback: all bus 1 if not derivable)
    baseline_assignment: Dict[Element, int] = {}
    if baseline_obs is not None and hasattr(baseline_obs, 'topo_vect') and hasattr(env, 'sub_info'):
        try:
            # Derive substation slice in topo_vect
            sub_counts = list(env.sub_info)
            # Assume sub_id indexes into sub_counts directly
            start = int(sum(sub_counts[:sub_id]))
            length = int(sub_counts[sub_id])
            sub_slice = baseline_obs.topo_vect[start:start+length]
            # We cannot reliably map each element type to an exact position; fallback: assign sequentially
            # in the same order we constructed elements.
            for i, el in enumerate(elements):
                if i < len(sub_slice):
                    baseline_assignment[el] = int(sub_slice[i])  # already 1 or 2
                else:
                    baseline_assignment[el] = 1
        except Exception:
            baseline_assignment = {el: 1 for el in elements}
    else:
        baseline_assignment = {el: 1 for el in elements}

    layouts: List[SubstationLayoutAction] = []

    # Enumerate all partitions (2^n). n kept small by reduction; if large, this could explode.
    for bitmask in range(1 << n):
        # Build assignment dict
        assignment: BusAssignment = {}
        for i, el in enumerate(elements):
            bus = 2 if (bitmask >> i) & 1 else 1
            assignment[el] = bus

        if drop_identity and all(assignment[el] == baseline_assignment.get(el, 1) for el in elements):
            continue  # Skip identity

        # Compute partition sets A (bus1) and B (bus2)
        bus1_elems = [el for el in elements if assignment[el] == 1]
        bus2_elems = [el for el in elements if assignment[el] == 2]

        if not _passes_symmetry(bus1_elems, bus2_elems, reduction, elements):
            continue
        if not _passes_reduction_rules(bus1_elems, bus2_elems, reduction):
            continue

        layout = _build_layout_action(sub_id, elements, assignment)
        layouts.append(layout)

    return layouts

def _passes_symmetry(bus1: List[Element], bus2: List[Element], reduction: str, ordered_elements: List[Element]) -> bool:
    """Always apply symmetry canonicalization for all reduction modes.

    Rationale: Even for N0 / N1 we want a stable, duplicate-free catalog where
    (A,B) and (B,A) are not both present. This preserves monotonic size
    relationships: SYM >= N0 >= N1.
    """
    key1 = tuple(bus1)
    key2 = tuple(bus2)
    return key1 >= key2

def _passes_reduction_rules(bus1: List[Element], bus2: List[Element], reduction: str) -> bool:
    if reduction == REDUCTION_SYM:
        return True  # No extra structural filtering

    def subset_ok(sub: List[Element]) -> bool:
        if len(sub) == 0:
            return True
        line_end_count = sum(1 for (t, _) in sub if t.startswith('line_'))
        if reduction == REDUCTION_N0:
            return len(sub) >= 2 and line_end_count >= 1
        if reduction == REDUCTION_N1:
            return len(sub) >= 2 and line_end_count >= 2
        return True

    return subset_ok(bus1) and subset_ok(bus2)

def _build_layout_action(sub_id: int, elements: List[Element], assignment: BusAssignment) -> SubstationLayoutAction:
    line_or_indices = [idx for (t, idx) in elements if t == 'line_or']
    line_ex_indices = [idx for (t, idx) in elements if t == 'line_ex']
    gen_indices = [idx for (t, idx) in elements if t == 'gen']
    load_indices = [idx for (t, idx) in elements if t == 'load']
    return SubstationLayoutAction(
        sub_id=sub_id,
        elements=list(elements),
        assignment=dict(assignment),
        line_or_indices=line_or_indices,
        line_ex_indices=line_ex_indices,
        gen_indices=gen_indices,
        load_indices=load_indices,
    )

