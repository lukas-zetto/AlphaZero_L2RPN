def summarize_catalog(catalog: ActionCatalog) -> str:
    parts = [f"ActionCatalog: reduction={catalog.reduction} drop_identity={catalog.drop_identity} total={catalog.size}"]
    for sub in catalog.substations:
        parts.append(f"  Sub {sub}: {catalog.per_sub_counts.get(sub,0)} actions")
    return "\n".join(parts)

