"""Action Catalog for Bus Switching Layouts

This module builds a catalog of *unitary bus switching actions* where each action
represents a full, atomic reconfiguration (layout) of a single substation's
switchable elements over its two busbars.

Key goals:
- Config-driven substation set and reduction mode (SYM, N0, N1)
- Exclude identity layouts (configurable)
- Stable ordering (deterministic indices)
- Easy future extension (line status toggles, multi-sub composites)
- Masking support (cooldowns / unsafe / illegal)

Assumptions & Notes:
- We assume `env.sub_info` is an iterable giving the number of elements per
  substation in topo_vect order; cumulative sums yield slices in observation.topo_vect.
- Element ordering inside a substation's topo slice is NOT strictly documented; we
  construct our own canonical ordering: (line_or, line_ex, gen, load) with ascending indices.
  Identity detection assumes this ordering; if actual topo_vect order differs, identity
  elimination still works logically because we derive the baseline buses per element using
  mappings by element type and index.
- Bus numbers in Grid2Op are 1 or 2. We store them directly.
- For cooldown masking we currently only check line switching cooldowns using
  `observation.time_before_cooldown_line`. Generators / loads typically have no cooldown
  for bus moves; placeholder hooks are provided.

Reduction Modes:
- SYM: Keep one representative per (A,B) partition under swapping A<->B.
- N0: For each non-empty bus subset S: |S|>=2 AND line_end_count(S)>=1
- N1: For each non-empty bus subset S: |S|>=2 AND line_end_count(S)>=2

Identity:
- If drop_identity=True we remove the layout matching the baseline topology (initial reset obs).

Extensibility Hooks:
- add_line_status_toggles(catalog, env): placeholder to append new non-topology actions
- compose_multi_substation(...): future composite generation

Author: Auto-generated by action space refactor assistant.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from typing import List, Dict, Tuple, Iterable, Optional, Any
import numpy as np

# Type aliases
Element = Tuple[str, int]  # (etype, index) where etype in {"line_or","line_ex","gen","load"}
BusAssignment = Dict[Element, int]  # bus number 1 or 2

REDUCTION_SYM = "SYM"
REDUCTION_N0 = "N0"
REDUCTION_N1 = "N1"
VALID_REDUCTION = {REDUCTION_SYM, REDUCTION_N0, REDUCTION_N1}

@dataclass
class SubstationLayoutAction:
    """Represents one full bus layout for a single substation."""
    sub_id: int
    elements: List[Element]  # stable ordered list
    assignment: BusAssignment  # maps each element to bus 1 or 2
    # Precomputed quick access lists per type for faster mask evaluation
    line_or_indices: List[int] = field(default_factory=list)
    line_ex_indices: List[int] = field(default_factory=list)
    gen_indices: List[int] = field(default_factory=list)
    load_indices: List[int] = field(default_factory=list)

    def apply(self, action_space) -> Any:
        """Create a Grid2Op action applying this layout.
        Only set elements whose bus differs from current; we cannot know current
        here without observation, so we set all to target bus (Grid2Op will ignore if same).
        
        Special case: sub_id=-1 means do-nothing action.
        """
        action = action_space()
        
        # Handle do-nothing action
        if self.sub_id == -1:
            return action  # Empty action = do nothing
        
        if self.line_or_indices:
            action.line_or_set_bus = [(idx, self.assignment[("line_or", idx)]) for idx in self.line_or_indices]
        if self.line_ex_indices:
            action.line_ex_set_bus = [(idx, self.assignment[("line_ex", idx)]) for idx in self.line_ex_indices]
        if self.gen_indices:
            action.gen_set_bus = [(idx, self.assignment[("gen", idx)]) for idx in self.gen_indices]
        if self.load_indices:
            action.load_set_bus = [(idx, self.assignment[("load", idx)]) for idx in self.load_indices]
        return action

@dataclass
class ActionCatalog:
    actions: List[SubstationLayoutAction]
    per_sub_counts: Dict[int, int]
    reduction: str
    substations: List[int]
    drop_identity: bool
    # Derived maps
    per_sub_offsets: Dict[int, Tuple[int, int]] = field(default_factory=dict)
    # Cache of applied Grid2Op actions per action_space identity
    _applied_cache: Dict[int, List[Any]] = field(default_factory=dict, repr=False)

    def __post_init__(self):
        offset = 0
        for sub in self.substations:
            count = self.per_sub_counts.get(sub, 0)
            self.per_sub_offsets[sub] = (offset, offset + count)
            offset += count

    @property
    def size(self) -> int:
        return len(self.actions)

    def sub_catalog(self, sub_id: int) -> List[SubstationLayoutAction]:
        start, end = self.per_sub_offsets[sub_id]
        return self.actions[start:end]

    def get_applied_actions(self, action_space) -> List[Any]:
        """Return cached Grid2Op actions for this catalog and action_space.

        Creating Grid2Op Action objects is relatively expensive; MCTS builds
        legal actions many times per simulation step. Since applying a layout
        only depends on the action_space (not the observation), we can prebuild
        and reuse them safely across the search.
        """
        key = id(action_space)
        cached = self._applied_cache.get(key)
        if cached is not None and len(cached) == self.size:
            return cached
        # Build and cache
        applied: List[Any] = []
        for layout in self.actions:
            try:
                applied.append(layout.apply(action_space))
            except Exception:
                # Skip actions that fail to materialize for this action_space
                # Keep alignment by continuing; but to preserve indices, we still append do-nothing
                # Here we choose to skip entirely; train_agent maps by index from valid_actions anyway.
                pass
        self._applied_cache[key] = applied
        return applied

